def summary() -> dict:
    """Coverage report: totals plus a per-module breakdown."""
    per_module = [
        {"module": letter, "title": title, "total": total,
         "implemented": sum(1 for f in FEATURES
                          if f.module == letter and f.status == "implemented")}
        for letter, title, total in MODULES
    ]
